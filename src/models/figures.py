from src.models.metrics import normalised_confusion

PALETTE = ["#4C72B0", "#DD8452", "#55A868", "#C44E52", "#8172B3"]


# ---------------------------------------------------------------------------
def plot_confusion_matrices(
    cm: Sequence[Sequence[int]],
    class_names: Sequence[str],
    out_path: Path,
    title: str = "",
) -> None:
    """Raw counts and row-normalised, side by side.

    Both are needed. The raw matrix is dominated by class 0 and makes the rare
    classes invisible; the normalised one (each row = per-class recall) shows
    that the model may be getting most of the rare cases wrong.
    """
    cm = np.asarray(cm, dtype=int)
    cm_norm = normalised_confusion(cm)
    n = len(class_names)

    fig, axes = plt.subplots(1, 2, figsize=(13, 5.4))

    for ax, matrix, fmt, name, cmap in (
        (axes[0], cm, "d", "Counts", "Blues"),
        (axes[1], cm_norm, ".2f", "Row-normalised (per-class recall)", "Blues"),
    ):
        im = ax.imshow(matrix, cmap=cmap, vmin=0,
                       vmax=matrix.max() if matrix.max() > 0 else 1)
        ax.set_title(name, fontsize=10)
        ax.set_xticks(range(n)); ax.set_yticks(range(n))
        ax.set_xticklabels(class_names, rotation=35, ha="right", fontsize=8)
        ax.set_yticklabels(class_names, fontsize=8)
        ax.set_xlabel("Predicted"); ax.set_ylabel("True")

        threshold = matrix.max() / 2 if matrix.max() > 0 else 0.5
        for i in range(n):
            for j in range(n):
                value = matrix[i, j]
                ax.text(j, i, format(value, fmt), ha="center", va="center", fontsize=8,
                        color="white" if value > threshold else "black")
        fig.colorbar(im, ax=ax, fraction=0.046, pad=0.04)

    fig.suptitle(title or "Confusion matrix (test split)", fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.95])
    fig.savefig(out_path, dpi=150, bbox_inches="tight")
    plt.close(fig)


