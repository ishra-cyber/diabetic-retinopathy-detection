def plot_per_class_recall(
    all_metrics: List[Dict[str, Any]],
    class_names: Sequence[str],
    out_path: Path,
) -> None:
    """Per-class recall for every architecture, grouped by class.

    This is where the imbalance shows: expect a tall bar for No DR and short
    ones for Mild and Severe, across all three models.
    """
    n = len(class_names)
    x = np.arange(n)
    width = 0.8 / max(len(all_metrics), 1)

    fig, ax = plt.subplots(figsize=(9.5, 4.8))
    for i, (metrics, colour) in enumerate(zip(all_metrics, PALETTE)):
        recalls = [pc["recall"] for pc in metrics["per_class"]]
        ax.bar(x + i * width - 0.4 + width / 2, recalls, width,
               label=metrics.get("backbone", metrics.get("run_name")),
               color=colour, edgecolor="black", linewidth=0.5)

    supports = [pc["support"] for pc in all_metrics[0]["per_class"]]
    ax.set_xticks(x)
    ax.set_xticklabels([f"{name}\n(n={s})" for name, s in zip(class_names, supports)],
                       fontsize=8)
    ax.set_ylabel("Recall (sensitivity)")
    ax.set_ylim(0, 1.05)
    ax.set_title("Per-class recall on the test split")
    ax.legend(fontsize=8)
    ax.grid(axis="y", alpha=0.25, linestyle=":")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


