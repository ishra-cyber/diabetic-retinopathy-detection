def plot_roc_curves(
    y_true: np.ndarray,
    probabilities: np.ndarray,
    class_names: Sequence[str],
    out_path: Path,
    title: str = "",
) -> None:
    """One-vs-rest ROC curve per class, with AUC in the legend."""
    from sklearn.metrics import auc, roc_curve

    y_true = np.asarray(y_true)
    fig, ax = plt.subplots(figsize=(6.6, 6))

    for label, (name, colour) in enumerate(zip(class_names, PALETTE)):
        binary = (y_true == label).astype(int)
        if binary.min() == binary.max():
            continue                      # class absent from this split
        fpr, tpr, _ = roc_curve(binary, probabilities[:, label])
        ax.plot(fpr, tpr, color=colour, linewidth=1.8,
                label=f"{label} {name} (AUC {auc(fpr, tpr):.3f})")

    ax.plot([0, 1], [0, 1], "k--", linewidth=1, alpha=0.5, label="chance")
    ax.set_xlabel("False positive rate")
    ax.set_ylabel("True positive rate")
    ax.set_title(title or "One-vs-rest ROC curves (test split)")
    ax.legend(fontsize=8, loc="lower right")
    ax.grid(alpha=0.25, linestyle=":")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


