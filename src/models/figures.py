def plot_model_comparison(comparison: pd.DataFrame, out_path: Path) -> None:
    """Headline metrics for the three architectures, side by side."""
    metrics = [("QWK", "QWK"), ("accuracy", "Accuracy"),
               ("balanced_acc", "Balanced acc."), ("F1_macro", "Macro F1")]

    fig, axes = plt.subplots(1, len(metrics), figsize=(15, 4.2), sharey=True)
    for ax, (col, label) in zip(axes, metrics):
        if col not in comparison.columns:
            ax.axis("off"); continue
        ax.bar(comparison["backbone"], comparison[col],
               color=PALETTE[: len(comparison)], edgecolor="black", linewidth=0.6)
        for i, value in enumerate(comparison[col]):
            ax.text(i, value + 0.012, f"{value:.3f}", ha="center", fontsize=8)
        ax.set_title(label, fontsize=10)
        ax.set_ylim(0, 1.05)
        ax.tick_params(axis="x", rotation=25, labelsize=8)
        ax.grid(axis="y", alpha=0.25, linestyle=":")
        ax.spines[["top", "right"]].set_visible(False)

    fig.suptitle("Architecture comparison on the held-out test split", fontsize=11)
    fig.tight_layout(rect=[0, 0, 1, 0.93])
    fig.savefig(out_path, dpi=150)
    plt.close(fig)
