def plot_error_distance(
    error_stats: Dict[str, Any],
    out_path: Path,
    title: str = "",
) -> None:
    """How far off the wrong answers are.

    The story this tells: most errors are off by one grade, which is why QWK
    stays high while plain accuracy looks unremarkable. Ordinal errors are not
    all equal, and this figure is the evidence.
    """
    counts = error_stats["error_distance_counts"]
    distances = sorted(counts)
    values = [counts[d] for d in distances]
    total = sum(values)

    fig, ax = plt.subplots(figsize=(7, 4.2))
    colours = ["#55A868"] + ["#DD8452"] * (len(distances) - 1)
    bars = ax.bar([str(d) for d in distances], values,
                  color=colours[: len(distances)], edgecolor="black", linewidth=0.6)
    for bar, value in zip(bars, values):
        if value:
            ax.annotate(f"{value}\n({value/total:.1%})",
                        xy=(bar.get_x() + bar.get_width() / 2, bar.get_height()),
                        xytext=(0, 3), textcoords="offset points",
                        ha="center", fontsize=8)

    ax.set_xlabel("|predicted grade − true grade|   (0 = correct)")
    ax.set_ylabel("Number of test images")
    ax.set_title(title or "Error magnitude on the test split")
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


